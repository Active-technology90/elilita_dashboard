export const printPayoutReceipt = (
  payout: PayoutData,
  t?: PayoutTranslator,
  locale = "en-US"
): boolean => {
  const html = generatePayoutReceiptHtml(payout, t, locale);
  const printWindow = window.open("", "_blank", "width=850,height=900");
  if (!printWindow) return false;
  printWindow.document.open();
  printWindow.document.write(html);
  printWindow.document.close();
  printWindow.focus();
  setTimeout(() => {
    printWindow.print();
  }, 350);
  return true;
};

export const downloadPayoutCsv = (
  payouts: PayoutData[],
  filename = "payout_receipts_export.csv",
  t?: PayoutTranslator,
  locale = "en-US"
): void => {
  const lang = resolveLang(locale);
  const L = (key: string, fallback: string) => tr(lang, t, key, fallback);

  const headers = [
    L("csv.receiptId", "Receipt ID"),
    L("csv.orderId", "Order ID"),
    L("csv.vendorCompany", "Vendor Company"),
    L("csv.companySlug", "Company Slug"),
    L("csv.grossAmount", "Gross Amount (ETB)"),
    L("csv.platformFee", "Platform Fee (ETB)"),
    L("csv.netPayout", "Net Payout (ETB)"),
    L("csv.paymentStatus", "Payment Status"),
    L("csv.paymentMethod", "Payment Method"),
    L("csv.scheduledDate", "Scheduled Date"),
    L("csv.paidDate", "Paid Date"),
    L("csv.reference", "Reference"),
  ];

  const csvEscape = (value: unknown): string =>
    `"${String(value ?? "").replace(/"/g, '""')}"`;

  const rows = payouts.map((p) => [
    p.id,
    p.vendor_order,
    csvEscape(p.company_name),
    csvEscape(p.company_slug),
    p.gross_amount,
    p.platform_fee,
    p.net_amount,
    csvEscape(
      L(
        STATUS_KEY[p.status] ?? STATUS_KEY.pending,
        STATUS_FALLBACK[p.status] ?? STATUS_FALLBACK.pending
      )
    ),
    csvEscape(
      getPaymentMethodLabel(p.vendor_order_details?.payment_method, lang, t)
    ),
    csvEscape(
      p.scheduled_at
        ? new Date(p.scheduled_at).toLocaleDateString(locale)
        : ""
    ),
    csvEscape(
      p.paid_at ? new Date(p.paid_at).toLocaleDateString(locale) : ""
    ),
    csvEscape(p.reference || ""),
  ]);

  const csvContent =
    "\uFEFF" +
    [headers.map(csvEscape).join(","), ...rows.map((r) => r.join(","))].join(
      "\r\n"
    );

  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};