/* Resolve a translation: passed-t first (if it actually translates),
   then built-in dict, then the English fallback string. */
const tr = (
  lang: Lang,
  t: PayoutTranslator | undefined,
  key: string,
  fallback: string
): string => {
  if (t) {
    const external = t(key, "");
    if (external && external !== key) return external;
  }
  return DICT[lang]?.[key] ?? fallback;
};

const resolveLang = (locale: string): Lang =>
  locale.toLowerCase().startsWith("am") ? "am" : "en";

const escapeHtml = (value: unknown): string =>
  String(value ?? "").replace(/[&<>"']/g, (char) => {
    const entities: Record<string, string> = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    };
    return entities[char];
  });

const formatAmount = (
  value: string | number | null | undefined,
  locale: string
): string =>
  Number(value || 0).toLocaleString(locale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  export const getStatusLabel = (
  status: PayoutData["status"],
  t?: PayoutTranslator,
  locale = "en-US"
): string => {
  const lang = resolveLang(locale);

  return tr(
    lang,
    t,
    STATUS_KEY[status] ?? STATUS_KEY.pending,
    STATUS_FALLBACK[status] ?? STATUS_FALLBACK.pending
  );
};

// ✅ toLocaleString (not toLocaleDateString) when time is included
const formatDateTime = (
  value: string | null | undefined,
  locale: string,
  fallback: string
): string => {
  if (!value) return fallback;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return fallback;
  return date.toLocaleString(locale, {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
};

